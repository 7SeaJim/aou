def _pad(grid):
    """补齐成矩形,并裁掉四周整行整列的空白。

    手写网格右边漏几个点很常见,与其数格子不如补齐;
    裁空白则是因为这些图是按「底边贴地」或「中心对齐」摆的,
    留一圈空行会让东西凭空浮在半空(海鸥、摊子都栽过)。
    """
    w = max(len(r) for r in grid)
    g = [r + '.' * (w - len(r)) for r in grid]
    while g and set(g[0]) == {'.'}: g.pop(0)
    while g and set(g[-1]) == {'.'}: g.pop()
    left = min(len(r) - len(r.lstrip('.')) for r in g)
    right = min(len(r) - len(r.rstrip('.')) for r in g)
    return [r[left:len(r) - right] for r in g]

SCENERY = {k: _pad(v) for k, v in SCENERY.items()}


