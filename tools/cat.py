"""折耳根 —— 常年游荡在海埂大坝的一只橘猫。

梦想也是去冰岛,所以跟哇鸥一起在摊上打工。不上班的时候就摊在大坝上睡觉。

名字是云南人都懂的那个梗:折耳根(鱼腥草)是本地菜里最有争议的一味,
爱的爱死恨的恨死 —— 拿来当一只谁都想撸又谁都撸不着的橘猫的名字正好。

两个姿势:
    cat_sleep  睡着的,团成一坨,尾巴绕过来盖住鼻子。摆在大坝甲板上
    cat_work   上班的,坐着,尾巴支在身侧。摆在出摊那一场的柜台后

橘猫用 Y/o 两档橘 + t 的深条纹 + w 的肚皮。**不用 R/r 那两档珊瑚色** ——
那是哇鸥嘴和脚的颜色,一个画面里两处红会打架。
"""


def canvas(w, h):
    return [['.'] * w for _ in range(h)]


def rows(g):
    return [''.join(r) for r in g]


def rect(g, x, y, w, h, c):
    for j in range(max(0, y), min(len(g), y + h)):
        for i in range(max(0, x), min(len(g[0]), x + w)):
            g[j][i] = c


def blob(g, cx, cy, rx, ry, c):
    """一个实心椭圆。猫身上没有直线,全靠这个堆"""
    for j in range(len(g)):
        for i in range(len(g[0])):
            if ((i - cx) / rx) ** 2 + ((j - cy) / ry) ** 2 <= 1:
                g[j][i] = c


def outline(g, c='K'):
    """给所有非空格子描一圈边。省得每个形状各描各的,接缝处还会露白"""
    h, w = len(g), len(g[0])
    out = [r[:] for r in g]
    for j in range(h):
        for i in range(w):
            if g[j][i] != '.':
                continue
            for dj, di in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                y, x = j + dj, i + di
                if 0 <= y < h and 0 <= x < w and g[y][x] not in ('.', c):
                    out[j][i] = c
                    break
    return out


def stamp(dst, src, ox, oy):
    """把一张小图盖到大图上,空格子不盖。"""
    for j, row in enumerate(src):
        for i, ch in enumerate(row):
            if ch == '.':
                continue
            if 0 <= oy + j < len(dst) and 0 <= ox + i < len(dst[0]):
                dst[oy + j][ox + i] = ch


def head_with_ears():
    """脑袋和两只耳朵。

    **脸不是圆的,是个钻石形。** 上一版用一个椭圆当脑袋,下巴一圆
    就成了人脸 —— 猫的脸最宽在颧骨那一线,往下很快收成一个小下巴,
    而且整体是**扁的**,宽比高多。一个圆脑袋无论耳朵怎么改都救不回来。

    **画在一起,只描一圈外边。** 脑袋描一圈、每只耳朵各描一圈的话,
    耳根那儿会多出一道线,看着像一颗人头上扣了两只猫耳。
    耳朵是脑袋长出来的,它俩中间本来就不该有线。

    但**整个「脑袋 + 耳朵」还是得带边**:它要压在身子上,而身子和它
    是同一块橙,不带边叠上去等于没画 —— 所以是「里头不描、外圈描一圈」。
    """
    h = canvas(16, 18)
    # 脸:自上而下的宽度。
    #
    # **收口要带弧度,而且是慢-快的弧。** 上一版从 13 一路匀速收到 4,
    # 收出来是一个尖楔子 —— 那是老鼠的吻部,不是猫脸。
    # 猫的脑门是**宽而平**的(耳朵之间那一片),颧骨最宽处连着三行不收,
    # 之后连着三行每行少 1、最后一行少 2,收到八格宽的小下巴就打住 ——
    # 下巴要小,但不能收成一个点。
    #
    # **收口的「加速度」决定下巴圆不圆。** 少 1、少 1、少 2、少 2 收出来的
    # 左下角是两级看得见的台阶;改成少 1、少 1、少 1、少 2,台阶就摊平成一道弧。
    FACE = [7, 9, 11, 11, 11, 10, 9, 7]
    for j, w in enumerate(FACE):
        rect(h, 7 - w // 2, 4 + j, w, 1, 'Y')
    # 耳朵小、矮、往两边靠。折耳猫的耳朵本来就是往前扣的一小片,
    # 又高又大的一对立在脑门正上方,那是老鼠
    for cx in (3, 10):
        for j, w in enumerate([2, 3, 3]):
            rect(h, cx - w // 2, 2 + j, w, 1, 'Y')
        rect(h, cx, 3, 1, 2, 'o')          # 耳朵里头
    return outline(h)


def sleeping():
    """睡着的橘猫,团成一坨。

    **就是两个椭圆**:小的那个是脑袋(连着耳朵),大的那个是身子,
    脑袋叠在身子左端。绕了几版才回到这么简单的一句话 ——

        v1 一根等粗的长椭圆 + 平铺的尾巴  →  毛毛虫,尾巴看不出是尾巴
        v2 身子和屁股两个圆挨着画         →  被 outline() 焊成一根管子
        v3 背拱得老高、尾梢挑到肩膀       →  睡熟的猫是塌下去的,不是弓起来的
        v4 压平 + 宽矮的耳朵              →  平成一块板,耳朵读成兔子
        v5 尖耳朵,为了不压身子把头外挪   →  耳朵尖得像天线
        v6 脑袋和耳朵各描各的边           →  耳根多一道线,像人头上扣了猫耳

    一条规律贯穿始终:**描边要按「一个东西」来描,不是按「一个图形」。**
    脑袋加耳朵是一个东西,里头不该有线;它和身子是两个东西,中间必须有线。
    """
    g = canvas(33, 24)
    blob(g, 19, 13.5, 12.5, 8, 'Y')        # 身子:一个大椭圆,背就是它的上缘
    # 背上的条纹跟着背的弧度走,越往屁股越短
    for x, y, h in ((17, 7, 4), (21, 7, 4), (25, 8, 3), (28, 10, 3)):
        rect(g, x, y, 1, h, 't')
    # 脑袋(连耳朵)整个压上来
    # 往下压,让下巴**搭在前爪和地板那条线上** —— 悬在半空的脑袋
    # 不是在睡,是在发呆。再往下一格的话下巴会掉到身子轮廓外边,
    # 看着像脑袋从身上滑下来了
    stamp(g, head_with_ears(), 0, 11)
    # 前爪:画在脑袋之后,从下巴底下露出来。**和肚皮之间要留出空档** ——
    # 两块白挨上就又并成一条白带子,前面就是栽在这儿
    rect(g, 12, 20, 5, 2, 'w')
    rect(g, 12, 22, 5, 1, 'K')
    rect(g, 17, 20, 1, 2, 'K')
    rect(g, 5, 15, 1, 2, 't'); rect(g, 9, 15, 1, 2, 't')     # 额头的纹
    # 肚皮和折在身下的前爪
    # 肚皮靠右,前爪单独一撮**从脸底下伸出来**。
    # 原来白色一直铺到 x=11、而脑袋右边到 x=13,白的直接盖在脸上,
    # 脸和肚子糊成一块。现在两块白各归各的:肚皮在身子底下,
    # 爪子贴着下巴,底下点一道边把它和身子分开
    blob(g, 23, 19, 4.5, 2, 'w')
    # 脸:两道闭着的眼 + 一个鼻头。**不画嘴** ——
    # 这个尺度上嘴只有两三格,画出来是脸上多了几个黑点,不是一张嘴
    rect(g, 3, 18, 3, 1, 'K')
    rect(g, 8, 18, 3, 1, 'K')
    rect(g, 6, 20, 2, 1, 'p')
    # 尾巴:从屁股上长出来,贴着肚子底下绕到前面。
    #
    #   连续      原来沿折线每隔两三格点一个方块,中间露出来的底色成了一道道
    #             竖缝,整条尾巴读成一截截拼起来的。现在把点连成线。
    #   只描下沿  上沿不描 —— 它和身子本来就是连着的,中间画一道线就成了
    #             「拼上去的一根皮带」。只有露在外面的下缘才需要边。
    #   边从格子推 逐格看「底下是不是空的」,是就在那儿点一笔。
    #             **不能沿着路径铺一条宽带** —— 斜着走的地方会把拐角那格也
    #             填上,而像素画里 (1,1) 接 (2,2) 只点这两格,中间的 (1,2)
    #             是不上色的。铺宽带等于把每个拐角都补成了直角。
    tail = [(30, 15), (30, 17), (29, 19), (27, 20), (24, 21),
            (20, 21), (17, 21), (14, 21)]
    path = []
    for i in range(len(tail) - 1):
        (x0, y0), (x1, y1) = tail[i], tail[i + 1]
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for t in range(steps + 1):
            path.append((round(x0 + (x1 - x0) * t / steps),
                         round(y0 + (y1 - y0) * t / steps)))
    cells = set()
    for x, y in path:
        for dx in range(2):
            for dy in range(2):
                cells.add((x + dx, y + dy))
    for x, y in cells:
        rect(g, x, y, 1, 1, 'o')
    for x, y in sorted(cells):
        if (x, y + 1) not in cells:
            rect(g, x, y + 1, 1, 1, 'K')      # 下沿
        if (x - 1, y) not in cells:
            rect(g, x - 1, y, 1, 1, 'K')      # 尖梢那头收个口
    return rows(outline(g))


def working():
    """上班的橘猫。坐在柜台后面,尾巴支在身侧。

    **比睡着那只小归小,但不能小成一撮。** 原来 18×24,站在 13×25 的客人
    旁边看着还没人家一个脑袋大 —— 一只坐着的猫本来就该比站着的人矮,
    但矮不等于瘦一圈。现在 24×32:坐高和人差不多齐肩,横过来比人宽,
    这才是猫的比例。

    脸沿用睡姿那一版的骨架:**钻石形、收口带弧度、耳朵小而矮**。
    两只都看得见(正面朝你),所以左右各一只。
    """
    g = canvas(24, 32)
    # 身子:坐着的猫是一个下宽上窄的梯形,不是一个圆
    for j, w in enumerate([10, 12, 14, 15, 16, 17, 17, 18, 18, 18, 18, 17]):
        rect(g, 12 - w // 2, 18 + j, w, 1, 'Y')
    # 脑袋:和睡姿同一套写法 —— 脑门宽而平,颧骨最宽连三行,收口带弧度
    for j, w in enumerate([9, 11, 13, 13, 13, 12, 11, 10, 8]):
        rect(g, 12 - w // 2, 8 + j, w, 1, 'Y')
    # 耳朵:小、矮、往两边靠。正面能看见两只
    for cx in (7, 16):
        for j, w in enumerate([2, 3, 3]):
            rect(g, cx - w // 2, 5 + j, w, 1, 'Y')
        rect(g, cx, 6, 1, 2, 'o')
    # 额头的纹
    rect(g, 10, 10, 1, 2, 't'); rect(g, 14, 10, 1, 2, 't')
    # 肩上的纹。**画在白胸之前**,而且靠两边 ——
    # 画在后面会横穿过白胸,读成胸口挂了两根棍
    for x, y in ((5, 20), (18, 20), (4, 24), (19, 24)):
        rect(g, x, y, 1, 3, 't')
    # 脸:上班时候眼睛是睁着的 —— 睡姿那只闭眼,这只得醒着
    rect(g, 8, 13, 2, 2, 'K'); rect(g, 14, 13, 2, 2, 'K')
    rect(g, 11, 15, 2, 1, 'p')             # 鼻头
    # 白围嘴 + 胸前那一片
    for j, w in enumerate([6, 8, 8, 7]):
        rect(g, 12 - w // 2, 16 + j, w, 1, 'w')
    for j, w in enumerate([8, 10, 10, 9, 8]):
        rect(g, 12 - w // 2, 21 + j, w, 1, 'w')
    # 前爪:两只并在身前
    rect(g, 6, 27, 4, 3, 'w'); rect(g, 14, 27, 4, 3, 'w')
    rect(g, 6, 30, 4, 1, 'K'); rect(g, 14, 30, 4, 1, 'K')
    # 尾巴:从右边身侧支出来,**根粗梢细**,只描外沿
    tail = [(19, 28), (21, 26), (22, 23), (22, 20), (21, 18)]
    path = []
    for i in range(len(tail) - 1):
        (x0, y0), (x1, y1) = tail[i], tail[i + 1]
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for t in range(steps + 1):
            path.append((round(x0 + (x1 - x0) * t / steps),
                         round(y0 + (y1 - y0) * t / steps)))
    cells = set()
    for i, (x, y) in enumerate(path):
        w = 3 if i < len(path) * 0.5 else 2
        for dx in range(w):
            for dy in range(w):
                cells.add((x + dx, y + dy))
    for x, y in cells:
        rect(g, x, y, 1, 1, 'o')
    # 外沿逐格推出来 —— 斜着走的地方不补拐角
    for x, y in sorted(cells):
        if (x + 1, y) not in cells:
            rect(g, x + 1, y, 1, 1, 'K')
        if (x, y - 1) not in cells:
            rect(g, x, y - 1, 1, 1, 'K')
    return rows(outline(g))


CAT = {
    'cat_sleep': sleeping(),
    'cat_work': working(),
}

for _k, _g in CAT.items():
    assert len({len(r) for r in _g}) == 1, f'{_k} 行宽不齐'
