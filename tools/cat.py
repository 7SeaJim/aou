"""折耳根 —— 常年游荡在海埂大坝的一只橘猫。

梦想也是去冰岛,所以跟哇鸥一起在摊上打工。不上班的时候就摊在大坝上睡觉。

名字是云南人都懂的那个梗:折耳根(鱼腥草)是本地菜里最有争议的一味,
爱的爱死恨的恨死 —— 拿来当一只谁都想撸又谁都撸不着的橘猫的名字正好。

两个姿势:
    cat_sleep  睡着的,团成一坨,尾巴绕过来盖住鼻子。摆在大坝甲板上
    cat_work   上班的,坐着,尾巴支在身侧。摆在出摊那一场的柜台后

橘猫用 Y/o 两档橘 + t 的深条纹 + w 的肚皮。**不用 R/r 那两档珊瑚色** ——
那是哇鸥嘴和脚的颜色,一个画面里两处红会打架。
"""


def canvas(w, h):
    return [['.'] * w for _ in range(h)]


def rows(g):
    return [''.join(r) for r in g]


def rect(g, x, y, w, h, c):
    for j in range(max(0, y), min(len(g), y + h)):
        for i in range(max(0, x), min(len(g[0]), x + w)):
            g[j][i] = c


def blob(g, cx, cy, rx, ry, c):
    """一个实心椭圆。猫身上没有直线,全靠这个堆"""
    for j in range(len(g)):
        for i in range(len(g[0])):
            if ((i - cx) / rx) ** 2 + ((j - cy) / ry) ** 2 <= 1:
                g[j][i] = c


def outline(g, c='K'):
    """给所有非空格子描一圈边。省得每个形状各描各的,接缝处还会露白"""
    h, w = len(g), len(g[0])
    out = [r[:] for r in g]
    for j in range(h):
        for i in range(w):
            if g[j][i] != '.':
                continue
            for dj, di in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                y, x = j + dj, i + di
                if 0 <= y < h and 0 <= x < w and g[y][x] not in ('.', c):
                    out[j][i] = c
                    break
    return out


def blob_out(g, cx, cy, rx, ry, c, edge='K'):
    """带描边的椭圆:先画大一圈的描边色,再画本体。

    **叠在同色形状上的东西必须自己带边。** 整体 outline() 只描最外面那圈,
    压在身子上的脑袋、压在身子上的耳朵,它俩和身子都是同一块橙 ——
    不自己带边的话,叠上去等于没画。
    """
    blob(g, cx, cy, rx + 1, ry + 1, edge)
    blob(g, cx, cy, rx, ry, c)


def ear(g, cx, ey):
    """一只耳朵,**自带描边**。

    右耳一定会压在身子上 —— 为了躲开身子把脑袋往外挪,只会挪出一只
    脖子特别长的猫。压上去没关系,描一圈边就分得开了:
    一块橙贴在橙上等于没画,一块橙**带着黑边**贴在橙上就是一只耳朵。

    形状是收口的圆三角,不是针尖。真猫的耳朵尖是有厚度的,
    收成一格宽的话在这个尺度上像两根天线。
    """
    W = [3, 3, 4, 5, 5]
    for j, w in enumerate(W):                       # 先铺一圈 K
        rect(g, cx - w // 2 - 1, ey + j - 1, w + 2, 2, 'K')
    for j, w in enumerate(W):                       # 再填耳廓
        rect(g, cx - w // 2, ey + j, w, 1, 'Y')
    rect(g, cx - 1, ey + 2, 2, 3, 'o')              # 耳朵里头


def sleeping():
    """睡着的橘猫,团成一坨。

    **就是两个椭圆**:小的那个是脑袋,大的那个是身子,脑袋叠在身子左端。
    绕了几版才回到这么简单的一句话 ——

        v1 一根等粗的长椭圆 + 平铺的尾巴  →  毛毛虫,尾巴看不出是尾巴
        v2 身子和屁股两个圆挨着画         →  被 outline() 焊成一根管子
        v3 背拱得老高、尾梢挑到肩膀       →  睡熟的猫是塌下去的,不是弓起来的
        v4 压平 + 宽矮的耳朵              →  平成一块板,耳朵读成兔子
        v5 尖耳朵 + 为了不压身子把头外挪  →  耳朵尖得像天线

    现在:一个大椭圆当身子(背自然是拱的),一个小椭圆当脑袋叠上去,
    耳朵该压就压、自己描边。
    """
    g = canvas(33, 24)
    blob(g, 19, 14, 12.5, 7.5, 'Y')        # 身子:一个大椭圆,背就是它的上缘
    # 耳朵画在脑袋**之前**:脑袋随后压上来盖住耳根,留在外面的就是耳廓 ——
    # 反过来先画脑袋的话,耳朵的描边会在脑袋顶上啃出两个缺口,
    # 「一个圆脑袋」那个形状当场就没了。
    # 所以耳朵要立得够高:露在脑袋轮廓之上四五格才看得出是耳朵。
    # 右耳压在身子上没关系,它自己带边
    ear(g, 4, 5)
    ear(g, 11, 5)
    # 脑袋:小椭圆,**带着自己的边**叠在身子左端。
    # 这一圈边就是「两个椭圆」这句话在画面上的样子 —— 少了它,
    # 脑袋和背是同一块橙,读出来只有一个形状
    blob_out(g, 7, 15, 6, 5.5, 'Y')
    # 背上的条纹跟着背的弧度走,越往屁股越短
    for x, y, h in ((17, 8, 4), (21, 8, 4), (25, 9, 3), (28, 11, 3)):
        rect(g, x, y, 1, h, 't')
    rect(g, 4, 12, 1, 2, 't'); rect(g, 9, 12, 1, 2, 't')
    # 肚皮和折在身下的前爪
    blob(g, 18, 19, 6, 2, 'w')
    rect(g, 11, 18, 4, 3, 'w')
    # 脸:两道闭着的眼 + 一个鼻头。**不画嘴** ——
    # 这个尺度上嘴只有两三格,画出来是脸上多了几个黑点,不是一张嘴
    rect(g, 4, 15, 3, 1, 'K')
    rect(g, 8, 15, 3, 1, 'K')
    rect(g, 6, 17, 2, 1, 'p')
    # 尾巴:贴着底边绕到前面,尖收在前爪旁边。
    # **不往上翘** —— 翘起来那一截在这个尺度上读成一片鱼鳍。
    # 先铺 K 再填 o,这道 K 就是尾巴和身子之间那条缝
    tail = [(29, 16), (29, 18), (27, 20), (24, 21), (21, 21), (18, 21),
            (16, 21), (14, 21)]
    for x, y in tail:
        rect(g, x - 1, y - 1, 4, 4, 'K')
    for x, y in tail:
        rect(g, x, y, 2, 2, 'o')
    rect(g, 13, 21, 2, 2, 'Y')             # 尖梢挑亮一格,收在这儿
    return rows(outline(g))


def working():
    """上班的橘猫。坐着,尾巴支在身侧 —— 一副「我在干活」的样子"""
    g = canvas(18, 24)
    blob(g, 9, 17, 6, 6, 'Y')              # 身子
    blob(g, 9, 8, 5.5, 5, 'Y')             # 脑袋
    # 耳朵
    rect(g, 4, 2, 2, 4, 'Y'); rect(g, 5, 1, 1, 2, 'Y')
    rect(g, 12, 2, 2, 4, 'Y'); rect(g, 12, 1, 1, 2, 'Y')
    # 额头的条纹
    rect(g, 7, 4, 1, 2, 't'); rect(g, 10, 4, 1, 2, 't')
    # 脸
    rect(g, 6, 8, 2, 2, 'K'); rect(g, 10, 8, 2, 2, 'K')     # 眼睛
    rect(g, 8, 11, 2, 1, 'p')                                # 鼻子
    rect(g, 7, 12, 1, 1, 'K'); rect(g, 10, 12, 1, 1, 'K')    # 嘴
    # 白围嘴和肚皮
    blob(g, 9, 18, 3.5, 4, 'w')
    # 前爪
    rect(g, 5, 21, 3, 2, 'w'); rect(g, 10, 21, 3, 2, 'w')
    # 尾巴支在右边
    for i, y in enumerate(range(21, 11, -1)):
        rect(g, 15 + (i // 4), y, 2, 1, 'o')
    return rows(outline(g))


CAT = {
    'cat_sleep': sleeping(),
    'cat_work': working(),
}

for _k, _g in CAT.items():
    assert len({len(r) for r in _g}) == 1, f'{_k} 行宽不齐'
