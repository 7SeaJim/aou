"""折耳根 —— 常年游荡在海埂大坝的一只橘猫。

梦想也是去冰岛,所以跟哇鸥一起在摊上打工。不上班的时候就摊在大坝上睡觉。

名字是云南人都懂的那个梗:折耳根(鱼腥草)是本地菜里最有争议的一味,
爱的爱死恨的恨死 —— 拿来当一只谁都想撸又谁都撸不着的橘猫的名字正好。

两个姿势:
    cat_sleep  睡着的,团成一坨,尾巴绕过来盖住鼻子。摆在大坝甲板上
    cat_work   上班的,坐着,尾巴支在身侧。摆在出摊那一场的柜台后

橘猫用 Y/o 两档橘 + t 的深条纹 + w 的肚皮。**不用 R/r 那两档珊瑚色** ——
那是哇鸥嘴和脚的颜色,一个画面里两处红会打架。
"""


def canvas(w, h):
    return [['.'] * w for _ in range(h)]


def rows(g):
    return [''.join(r) for r in g]


def rect(g, x, y, w, h, c):
    for j in range(max(0, y), min(len(g), y + h)):
        for i in range(max(0, x), min(len(g[0]), x + w)):
            g[j][i] = c


def blob(g, cx, cy, rx, ry, c):
    """一个实心椭圆。猫身上没有直线,全靠这个堆"""
    for j in range(len(g)):
        for i in range(len(g[0])):
            if ((i - cx) / rx) ** 2 + ((j - cy) / ry) ** 2 <= 1:
                g[j][i] = c


def outline(g, c='K'):
    """给所有非空格子描一圈边。省得每个形状各描各的,接缝处还会露白"""
    h, w = len(g), len(g[0])
    out = [r[:] for r in g]
    for j in range(h):
        for i in range(w):
            if g[j][i] != '.':
                continue
            for dj, di in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                y, x = j + dj, i + di
                if 0 <= y < h and 0 <= x < w and g[y][x] not in ('.', c):
                    out[j][i] = c
                    break
    return out


def sleeping():
    """睡着的橘猫,**团成一个球**。

    返工过两次,记下来为什么最后是这个样子:

    第一版身子是一个从头到尾一样粗的长椭圆,尾巴贴着底边平铺成一道细杠 ——
    整个下半截读成一条毛毛虫,尾巴根本看不出是尾巴。
    第二版加了个屁股包,但两个圆挨着画完被 outline 焊成了一整块,
    轮廓还是一根管子;尾巴绕到底下之后又和肚皮的白连成一片。

    这一版换了三个做法:

        换姿势    从「摊平的一条」改成「团起来的一个球」——
                  28×20 而不是 32×19。**猫睡着的招牌轮廓是圆的,不是长的。**
        高低差    屁股在右上顶起来,脑袋在左下埋下去,轮廓一高一低,
                  一眼看得出哪头是头
        尾巴自带边 尾巴先铺一圈 K 再填色,**自己带一道缝**。
                  只靠整体 outline 的话它和身子是连着的,等于没画
    """
    g = canvas(30, 21)
    blob(g, 17, 11, 10.5, 7, 'Y')          # 蜷起来的身子
    blob(g, 22, 10, 7.5, 6.5, 'Y')         # 屁股顶在右上
    # 脑袋**探出身子左边**。缩在身子里的话它和背连成一片,
    # 耳朵也就没地方立 —— 一只看不见耳朵的猫,是一坨面包
    blob(g, 6, 14, 5.5, 5, 'Y')
    # 折耳:往前扣的,只支起一点点。立在脑袋顶上,越过身子的轮廓
    rect(g, 2, 9, 3, 3, 'Y'); rect(g, 3, 8, 2, 2, 'Y')
    rect(g, 8, 9, 3, 3, 'Y'); rect(g, 8, 8, 2, 2, 'Y')
    # 脖子那道缝:不划这一刀,脑袋和背是同一块橙色
    for x, y in ((11, 9), (11, 11), (11, 13), (12, 15), (12, 17)):
        rect(g, x, y, 1, 2, 'o')
    # 背上的条纹跟着背的弧度走,越往屁股越短
    for x, y, h in ((15, 5, 4), (19, 4, 4), (23, 5, 3), (26, 7, 3)):
        rect(g, x, y, 1, h, 't')
    rect(g, 4, 10, 1, 3, 't'); rect(g, 8, 10, 1, 3, 't')
    # 肚皮和折在身下的前爪
    blob(g, 15, 16, 6, 2.5, 'w')
    rect(g, 9, 16, 4, 3, 'w')
    # 闭着的眼睛和鼻子
    rect(g, 3, 14, 3, 1, 'K')
    rect(g, 7, 14, 3, 1, 'K')
    rect(g, 5, 16, 2, 1, 'p')
    # 尾巴:从屁股右侧绕过底下,梢子挑到脸旁边翘起来。
    # 先铺 K 再填 o —— 这道 K 就是尾巴和身子之间那条缝
    tail = [(28, 12), (28, 14), (27, 16), (25, 18), (22, 19), (19, 19),
            (17, 19), (15, 19), (13, 19)]
    for x, y in tail:
        rect(g, x - 1, y - 1, 4, 4, 'K')
    for x, y in tail:
        rect(g, x, y, 2, 2, 'o')
    # 梢子在身子右后方翘起来一截,不再绕到脸前面 ——
    # 绕一整圈的话它贴着肚皮的白走,两条浅色挨在一起又糊成一片
    rect(g, 27, 8, 4, 5, 'K')
    rect(g, 28, 9, 2, 4, 'Y')
    return rows(outline(g))


def working():
    """上班的橘猫。坐着,尾巴支在身侧 —— 一副「我在干活」的样子"""
    g = canvas(18, 24)
    blob(g, 9, 17, 6, 6, 'Y')              # 身子
    blob(g, 9, 8, 5.5, 5, 'Y')             # 脑袋
    # 耳朵
    rect(g, 4, 2, 2, 4, 'Y'); rect(g, 5, 1, 1, 2, 'Y')
    rect(g, 12, 2, 2, 4, 'Y'); rect(g, 12, 1, 1, 2, 'Y')
    # 额头的条纹
    rect(g, 7, 4, 1, 2, 't'); rect(g, 10, 4, 1, 2, 't')
    # 脸
    rect(g, 6, 8, 2, 2, 'K'); rect(g, 10, 8, 2, 2, 'K')     # 眼睛
    rect(g, 8, 11, 2, 1, 'p')                                # 鼻子
    rect(g, 7, 12, 1, 1, 'K'); rect(g, 10, 12, 1, 1, 'K')    # 嘴
    # 白围嘴和肚皮
    blob(g, 9, 18, 3.5, 4, 'w')
    # 前爪
    rect(g, 5, 21, 3, 2, 'w'); rect(g, 10, 21, 3, 2, 'w')
    # 尾巴支在右边
    for i, y in enumerate(range(21, 11, -1)):
        rect(g, 15 + (i // 4), y, 2, 1, 'o')
    return rows(outline(g))


CAT = {
    'cat_sleep': sleeping(),
    'cat_work': working(),
}

for _k, _g in CAT.items():
    assert len({len(r) for r in _g}) == 1, f'{_k} 行宽不齐'
